import urllib.request
import json

def test():
    h = json.loads(urllib.request.urlopen('http://localhost:3001/api/health').read().decode())
    print('1. Express Health:', h.get('status'))

    req_s = urllib.request.Request('http://localhost:3001/api/search', data=json.dumps({'query': 'Python loops'}).encode(), headers={'Content-Type': 'application/json'})
    s = json.loads(urllib.request.urlopen(req_s).read().decode())
    print('2. Search Results Count:', len(s.get('results', [])))

    req_c = urllib.request.Request('http://localhost:3001/api/execute-code', data=json.dumps({'language': 'python', 'code': 'print("Calculated: 25")'}).encode(), headers={'Content-Type': 'application/json'})
    c = json.loads(urllib.request.urlopen(req_c).read().decode())
    print('3. Code Execution Output:', c.get('stdout').strip())

    req_i = urllib.request.Request('http://localhost:3001/api/image/generate', data=json.dumps({'prompt': 'Cosmic nebula'}).encode(), headers={'Content-Type': 'application/json'})
    img = json.loads(urllib.request.urlopen(req_i).read().decode())
    print('4. Image Generated by:', img.get('provider'))

    front = urllib.request.urlopen('http://localhost:5173/').getcode()
    print('5. Frontend Status Code:', front)

if __name__ == '__main__':
    test()
